// ─── Избранные: житель видел, как игрок поднялся ─────────────────────────────
//
// По канону вечная реинкарнация дана лишь избранным - тем, кто должен стать вехой в истории и
// предзнаменованием конца времён. Игроки и есть избранные. Житель, видевший возрождение, помнит это:
// отсюда пойдут цепочки поручений и главные разговоры.

const TC_SEEN_R = 48                                  // в каком радиусе житель видит возрождение

function tcWitness(player) {
    var level = player.level
    if (!level || typeof RAID_AABBClass === "undefined") return 0
    var seen = 0
    try {
        var box = new RAID_AABBClass(player.getX() - TC_SEEN_R, player.getY() - 16, player.getZ() - TC_SEEN_R,
            player.getX() + TC_SEEN_R, player.getY() + 16, player.getZ() + TC_SEEN_R)
        level.getEntities(player, box).forEach(e => {
            var w = null
            try { w = rlSettlerOf(e) } catch (ex) { w = null }
            if (!w) return
            if (!e.getTags().contains("tfg_saw_rise")) e.addTag("tfg_saw_rise")
            var v = w.v
            if (!v.rose) v.rose = {}
            var key = String(player.uuid)
            if (!v.rose[key]) v.rose[key] = {}
            v.rose[key][w.sid] = (Number(v.rose[key][w.sid]) || 0) + 1
            seen++
        })
        if (seen) global.TFG_SETTLERS.save()
    } catch (e) { tcLog("свидетели возрождения: " + e) }
    return seen
}

/** Сколько раз этот житель видел возрождение этого игрока. */
function tcSawRise(ctx) {
    var w = tcSettler(ctx)
    if (!w) return 0
    var r = w.v.rose && w.v.rose[String(ctx.player.uuid)]
    return r ? (Number(r[w.sid]) || 0) : 0
}

PlayerEvents.respawned(event => {
    try {
        var n = tcWitness(event.player)
        if (n > 0) tcLog(String(event.player.username) + ": возрождение видели жителей - " + n)
    } catch (e) { tcLog("возрождение: " + e) }
})

