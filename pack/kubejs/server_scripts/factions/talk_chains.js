/**
 * ЦЕПОЧКИ РАЗГОВОРОВ. До этого ответ жителя был одной репликой из списка - по сути случайной.
 * Здесь разговор идёт шагами: житель говорит, игрок выбирает ответ, от ответа зависит, что будет
 * дальше. Шаги связаны между собой, ветки закрываются условиями (сословие, вера народа, отношение,
 * что игрок уже знает), а узнанное запоминается у игрока и открывает следующие цепочки.
 *
 * УСТРОЙСТВО. Окно разговора (dialogue.js) умеет вложенный выбор - dlgChoice(ctx, приглашение, пункты).
 * На нём и стоит движок: шаг = реплики + пункты ответа, пункт ведёт на другой шаг. Поэтому ни окно,
 * ни уже озвученные реплики не тронуты: цепочки просто добавляют свои пункты в список жителя.
 *
 * ЧТО ЗАПОМИНАЕТСЯ (данные игрока, tfg_talk):
 *   know - что игрок узнал о мире (ключи ниже). На них опираются условия цепочек, поручения и книги.
 *   done - какие цепочки пройдены (чтобы не водить по той же дважды, но можно переспросить короче).
 *   open - незаконченный разговор: ключ жителя -> "цепочка:шаг", чтобы вернуться к нему позже.
 *
 * КАНОН - TFG-лор.md (28.10.2026). Коротко, чтобы не путать: бытие и небытие - два состояния, а не
 * места; Твердь - мир живых, созданный в бытии; мир мёртвых - в небытии; Отмель - третий пограничный
 * мир, куда спускаются упокоенные; апокалипсис - Выход Смерти; пир достанется одному колену.
 * Слова «Пустота» в каноне нет. Названия народов не переводятся: эшлендеры - эшлендеры.
 */

