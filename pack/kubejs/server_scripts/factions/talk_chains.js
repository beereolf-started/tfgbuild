/** Ключ жителя для записи незаконченного разговора: поселение и номер жителя, иначе uuid существа. */
function tcWho(ctx) {
    var w = tcSettler(ctx)
    if (w) return w.v.id + "/" + w.sid
    try { return String(ctx.trader.uuid) } catch (e) { return "?" }
}

function tcSettler(ctx) {
    try { return rlSettlerOf(ctx.trader) } catch (e) { return null }
}

/** Запись жителя в поселении (имя, роль, пол) или null. */
function tcPerson(ctx) {
    var w = tcSettler(ctx)
    if (!w) return null
    var list = w.v.settlers || []
    for (var i = 0; i < list.length; i++) if (list[i].id === w.sid) return list[i]
    return null
}

function tcIsSettler(ctx) {
    try { return ctx.trader.getTags().contains("tfg_settler") } catch (e) { return false }
}

/** Сословие жителя: «знать», «военные», «простолюдины» (settlers.js). */
function tcEstate(ctx) {
    var s = tcPerson(ctx)
    try { return s ? String(global.TFG_SETTLERS.estateOf(s)) : "простолюдины" } catch (e) { return "простолюдины" }
}

/** Мнение жителя об игроке: −100..+100 (relations.js). */
function tcOpinion(ctx) {
    var w = tcSettler(ctx), s = tcPerson(ctx)
    if (!w || !s) return Number(ctx.rep) || 0
    try { return Number(global.TFG_RELATIONS.opinion(ctx.player, w.v, s)) } catch (e) { return 0 }
}

/** Народ жителя: alliance | ash | marvins | wind (или null у одиночек). */
function tcFaith(ctx) {
    var w = tcSettler(ctx)
    return w ? String(w.v.faction) : (ctx.faction ? String(ctx.faction) : null)
}

/** Священник ли: роль жителя из settlers.js. */
function tcIsPriest(ctx) {
    var s = tcPerson(ctx)
    if (!s) return false
    var r = String(s.role || "")
    return r.indexOf("священник") >= 0 || r.indexOf("патриарх") >= 0 || r.indexOf("монах") >= 0
}

function tcIsRuler(ctx) {
    var s = tcPerson(ctx)
    return !!s && String(s.role || "").indexOf("правитель") >= 0
}

/** Грамотный ли - кто может ссылаться на книги (знать и священники, военные через одного). */
function tcLettered(ctx) {
    var e = tcEstate(ctx)
    if (tcIsPriest(ctx) || e === "знать") return true
    var s = tcPerson(ctx)
    return e === "военные" && !!s && rlHash(s.name + "lit") % 2 === 0
}

/** Болтливость 0..1 от имени - насколько охотно житель вдаётся в подробности. */
function tcChatty(ctx) {
    var s = tcPerson(ctx)
    return s ? (rlHash(s.name + "chat") % 100) / 100 : 0.5
}

/** Сдвинуть личное отношение жителя к игроку (с пометкой «за что»). */
function tcNote(ctx, d, why) {
    var w = tcSettler(ctx)
    if (!w) return
    try { global.TFG_RELATIONS.note(w.v, ctx.player, w.sid, d, why) } catch (e) { }
}

// ─── Движок ──────────────────────────────────────────────────────────────────

const TC_CHAINS = []

function tcChain(id) {
    for (var i = 0; i < TC_CHAINS.length; i++) if (TC_CHAINS[i].id === id) return TC_CHAINS[i]
    return null
}

function tcText(v, ctx) { return typeof v === "function" ? v(ctx) : v }

/** Пройти шаг цепочки: реплики, последствия, затем варианты ответа. */
function tcStep(ctx, chainId, stepId) {
    var chain = tcChain(chainId)
    if (!chain) return
    var step = chain.steps[stepId]
    if (!step) { tcEnd(ctx, chain); return }

    // где игрок остановился - чтобы вернуться, если разговор прервали
    var o = tcDataOf(ctx.player)
    o.open[tcWho(ctx)] = chainId + ":" + stepId
    tcSave(ctx.player, o)

    var say = tcText(step.say, ctx)
    if (say) (Array.isArray(say) ? say : [say]).forEach(line => { if (line) dlgSay(ctx, String(line)) })
    var note = tcText(step.note, ctx)
    if (note) dlgNote(ctx, String(note))
    if (step.learn) (Array.isArray(step.learn) ? step.learn : [step.learn]).forEach(k => tcLearn(ctx, k))
    if (step.do) { try { step.do(ctx) } catch (e) { tcLog(chainId + "/" + stepId + ": " + e) } }

    var opts = (step.opts || []).filter(op => {
        try { return !op.if || op.if(ctx) } catch (e) { return false }
    })
    if (!opts.length) { tcEnd(ctx, chain); return }

    dlgChoice(ctx, step.ask ? String(tcText(step.ask, ctx)) : null, opts.map(op => ({
        label: String(tcText(op.label, ctx)),
        hint: op.hint ? String(tcText(op.hint, ctx)) : null,
        run: c => {
            if (op.do) { try { op.do(c) } catch (e) { tcLog(chainId + " ответ: " + e) } }
            if (op.note) dlgNote(c, String(tcText(op.note, c)))
            if (op.go) tcStep(c, chainId, op.go)
            else tcEnd(c, chain)
        },
    })))
}

/** Цепочка кончилась: отметить пройденной и вернуть игрока в обычное меню жителя. */
function tcEnd(ctx, chain) {
    if (chain) tcMarkDone(ctx, chain.id)
    try { dlgRender(ctx.player, ctx.sess, null) } catch (e) { }
}

/** Доступна ли цепочка этому жителю и этому игроку. */
function tcAvailable(ctx, chain) {
    if (!tcIsSettler(ctx)) return false
    try {
        if (chain.show && !chain.show(ctx)) return false
        if (chain.need && !chain.need(ctx)) return false
    } catch (e) { return false }
    if (chain.once && tcDone(ctx.player, chain.id)) return false
    return true
}

