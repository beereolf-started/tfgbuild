function tcDataOf(player) {
    try {
        var o = JSON.parse(String(player.persistentData.getString("tfg_talk")) || "{}")
        if (!o.know) o.know = {}
        if (!o.done) o.done = {}
        if (!o.open) o.open = {}
        return o
    } catch (e) { return { know: {}, done: {}, open: {} } }
}

function tcSave(player, o) {
    try { player.persistentData.putString("tfg_talk", JSON.stringify(o)) } catch (e) { tcLog("не сохранить: " + e) }
}

function tcLog(text) { try { console.log("[цепочки] " + text) } catch (e) { } }

function tcKnows(player, key) { return !!tcDataOf(player).know[key] }

/** Запомнить узнанное и сказать об этом серой строкой - чтобы игрок видел, что разговор что-то дал. */
function tcLearn(ctx, key) {
    var o = tcDataOf(ctx.player)
    if (o.know[key]) return false
    o.know[key] = Math.floor(tcDay(ctx.player))
    tcSave(ctx.player, o)
    dlgNote(ctx, "Вы узнали: " + (TC_KNOW[key] || key) + ".")
    return true
}

function tcDone(player, id) { return !!tcDataOf(player).done[id] }

function tcMarkDone(ctx, id) {
    var o = tcDataOf(ctx.player)
    o.done[id] = Math.floor(tcDay(ctx.player))
    delete o.open[tcWho(ctx)]
    tcSave(ctx.player, o)
}

function tcDay(player) { try { return Number(player.level.getTime()) / 24000 } catch (e) { return 0 } }

