const TB_READERS = ["правитель", "бард", "торговец"]

/** Грамотен ли житель: знать, правители, барды, торговцы - всегда; военные - чаще, простолюдины - реже. */
function tbLiterate(v, s) {
    if (TB_READERS.indexOf(s.role) >= 0) return true
    var estate = global.TFG_SETTLERS.estateOf(s)
    if (estate === "знать") return true
    var roll = rlHash(v.id + "#" + s.id + "lit") % 100
    return roll < (estate === "военные" ? 70 : 40)
}

