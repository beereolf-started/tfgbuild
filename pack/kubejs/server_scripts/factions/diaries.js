// ─── Женский род ─────────────────────────────────────────────────────────────
//
// Действие автора почти всегда начинает предложение («Пахал до темноты», «Решил копить»), а чужое - стоит
// после имени («Бран помог»). Поэтому у жительницы переводим в женский род только глагол в начале предложения.
const DY_FEM_KEEP = ["Снился", "Родился", "Был", "Пол", "Стол", "Ствол", "Угол", "Частокол", "Прицел", "Орёл", "Котёл", "Посол"]
const DY_FEM_THREAD = ["Приглянулся мне один. Не знаю, как и подступиться.", "Он подарил мне ленту. Взяла.", "Его отец сказал, что я ему не пара. Обидно.",
    "Сговорились! Свадьба по осени. Не верю своему счастью."]

function dyFemWord(w) {
    if (DY_FEM_KEEP.indexOf(w) >= 0 || w.length < 3) return w
    if (/лся$/.test(w)) return w.replace(/лся$/, "лась")
    if (/шёл$/.test(w)) return w.replace(/шёл$/, "шла")
    if (/чёл$/.test(w)) return w.replace(/чёл$/, "чла")
    if (/вёл$/.test(w)) return w.replace(/вёл$/, "вела")
    if (/лёл$/.test(w)) return w.replace(/лёл$/, "лела")
    if (/л$/.test(w)) return w + "а"
    return w
}

// «Не купил», «Опять сорвался», «Снова ходил» - частица перед глаголом в начале предложения
const DY_FEM_LEAD = /(^|[.!?…]\s+)((?:Не|Опять|Снова|Сам|Тоже|Едва|Потом|Весь день|Всю ночь|Полдня|Утром|Вечером|Ночью)\s+)?([А-ЯЁа-яё]+)(?=[\s,.!?…])/g

function dyFem(text) {
    return String(text).replace(DY_FEM_LEAD, (m, pre, lead, w) => {
        if (!lead && !/^[А-ЯЁ]/.test(w)) return m
        var out = lead ? w : dyFemWord(w)
        if (lead && /(л|лся)$/.test(w)) out = dyFemWord(w)
        return pre + (lead ? lead.replace("Сам ", "Сама ") : "") + out
    }).replace(/Сама виноват(?![а-я])/g, "Сама виновата")
}

/** Дневник жителя s поселения v - подписанная книга. */
function dyDiary(level, v, s) {
    var site = null
    try { site = lrSiteOfVillage(v.id) } catch (e) { }
    var estate = global.TFG_SETTLERS.estateOf(s)
    var noble = estate === "знать"
    var name = id => { var o = v.settlers.filter(x => x.id === id)[0]; return o ? o.name : "кто-то" }
    var seed = String(v.id) + "#" + s.id
    var hash = k => { try { return rlHash(seed + k) } catch (e) { return Math.floor(Math.random() * 1e6) } }
    var moods = Object.keys(DY_MOODS)
    var mood = moods[hash("mood") % moods.length]
    var threadIx = hash("thread") % DY_THREADS.length
    var thread = s.female && threadIx === 2 ? DY_FEM_THREAD : DY_THREADS[threadIx]
    var parts = []
    parts.push("Дневник " + s.name + ". " + (site ? site.name + ", " : "") + "год " + DY_YEAR + " от Первого Камня.")
    parts.push(dyPick(noble ? DY_NOBLE_START : DY_PLAIN_START))

    // дни года - по возрастанию
    var count = noble ? 20 + Math.floor(Math.random() * 9) : 14 + Math.floor(Math.random() * 7)
    var days = []
    while (days.length < count) { var d = 1 + Math.floor(Math.random() * 360); if (days.indexOf(d) < 0) days.push(d) }
    days.sort((a, b) => a - b)
    var entries = days.map(d => ({ day: d, lines: [] }))
    var at = d => entries.reduce((best, e) => Math.abs(e.day - d) < Math.abs(best.day - d) ? e : best, entries[0])
    var any = () => entries[Math.floor(Math.random() * entries.length)]

    // история года: четыре шага - в начале, на трети, на двух третях и в конце года
    ;[0, Math.floor(count / 3), Math.floor(2 * count / 3), count - 1].forEach((ix, k) => entries[ix].lines.push(thread[k]))
    // настоящие события летописи - в свои дни
    ;(v.relLog || []).filter(x => x.a === s.id || x.b === s.id).slice(-10).forEach(x => {
        var t = LB_DIARY_EVENT[x.kind]
        if (t) at(x.day % 360 + 1).lines.push(dyPick(t).replace("{b}", name(x.a === s.id ? x.b : x.a)))
    })
    // секреты - в разные дни
    try {
        tkSecrets(v, s).forEach(sec => any().lines.push(dyPick(DY_SECRET).replace("{n}", s.name).replace("{t}", sec.text)))
    } catch (e) { }
    // вести округи
    if (site && site.events) site.events.slice(-4).forEach(e => any().lines.push("В округе толкуют: " + String(e.text) + "."))

    var links = []
    try { links = rlLinks(v, s.id) } catch (e) { }
    var read = []
    try { read = tbRead(v, s) } catch (e) { }
    var literate = true
    try { literate = tbLiterate(v, s) } catch (e) { }
    var faith = []
    try { faith = (TK_FAITH[v.faction] || []).concat(TK_FAITH_COMMON) } catch (e) { }

    var roleDeck = dyDeck((DY_ROLE[s.role] || DY_ROLE_DEFAULT).concat(DY_ROLE_MORE[s.role] || []))
    var omenDeck = dyDeck(DY_OMENS.concat(DY_OMENS_MORE)), faithDeck = dyDeck(faith.length ? faith : ["Всевышний видит."])
    var moodDeck = dyDeck(DY_MOODS[mood])
    var extraDeck = dyDeck(DY_DREAMS.concat(DY_PRICES, DY_CARAVAN, DY_FEARS))
    var farm = {}, weather = {}, food = {}, feast = {}
    DY_SEASONS.forEach(se => {
        farm[se] = dyDeck(DY_FARM[se])
        weather[se] = dyDeck(DY_WEATHER[se].concat(DY_WEATHER_MORE[se] || []))
        food[se] = dyDeck(DY_FOOD[se] || ["Ели, что было."])
        feast[se] = dyDeck(DY_FEAST[se] || ["Праздник. Отдыхали."])
    })
    var farmAny = dyDeck(DY_ROLE["крестьянин"].concat(DY_ROLE_MORE["крестьянин"] || []))
    var sayings = read.filter(b => TB_SAY[b.id]).map(b => TB_SAY[b.id])
    var bookDeck = dyDeck(sayings.length ? sayings : ["Книга Тверди - всему начало."])
    var linkDecks = {}
    var feastDone = {}
    entries.forEach(en => {
        var season = DY_SEASONS[Math.floor((en.day - 1) / 90)]
        var work = () => s.role === "крестьянин" ? (Math.random() < 0.3 ? farmAny() : farm[season]()) : roleDeck()
        var lines = [work()]
        if (Math.random() < 0.25) lines.push(work())
        if (Math.random() < 0.5) lines.push(moodDeck())
        if (Math.random() < 0.45) lines.push(Math.random() < 0.3 ? omenDeck() : weather[season]())
        if (links.length && Math.random() < 0.45) {
            var l = dyPick(links)
            var type = DY_LINK[l.type] ? l.type : (l.mine < -30 ? "enemy" : "friend")
            if (!linkDecks[type]) linkDecks[type] = dyDeck(DY_LINK[type])
            lines.push(linkDecks[type]().replace("{b}", name(l.other)))
        }
        if (Math.random() < 0.3) {
            if (literate && sayings.length && Math.random() < 0.6) lines.push(dyPick(DY_BOOK) + bookDeck())
            else if (!literate && Math.random() < 0.5) lines.push(dyPick(DY_ILLITERATE))
            else lines.push(faithDeck())
        }
        // праздник - раз за время года, еда, сны, цены, караваны, страхи
        if (!feastDone[season] && Math.random() < 0.35) { feastDone[season] = true; lines.push(feast[season]()) }
        else if (Math.random() < 0.25) lines.push(food[season]())
        if (Math.random() < 0.3) lines.push(extraDeck())
        en.lines = lines.concat(en.lines)
        // знать пишет пространнее
        if (noble && Math.random() < 0.5) en.lines.push(faithDeck())
        var body = en.lines.filter(x => !!x).join(" ")
        parts.push("День " + en.day + ", " + season + ". " + (s.female ? dyFem(body) : body))
    })

    // что он думает об игроках
    var pm = v.pmem || {}
    for (var uuid in pm) {
        var dd = pm[uuid][s.id]
        if (!dd) continue
        var pname = "чужак"
        try { var pl = level.getServer().getPlayerList().getPlayer(LB_UUID.fromString(uuid)); if (pl) pname = String(pl.username) } catch (e) { }
        parts.push((dd < 0 ? dyPick(LB_DIARY_PLAYER_BAD) : dyPick(LB_DIARY_PLAYER_GOOD)).replace("{p}", pname))
    }
    parts.push(s.female ? dyFem(dyPick(DY_END)) : dyPick(DY_END))
    return lbMake({ id: "diary", title: "Дневник " + s.name, author: s.name, text: parts.join("\n\n"),
        spine: noble ? "clasp" : "plain", value: noble ? 40 : 8 })
}

// ─── Замена старых коротких дневников ────────────────────────────────────────
//
// Поселения, где дневники уже лежат, получают новые один раз (v.diariesV2): старый дневник жителя в его
// сундуке меняется на новый. Записи о кладах были в старом - ссылка снимается, и stashes.js кладёт её заново.

function dyRefresh(level, v) {
    var n = 0
    v.settlers.forEach(s => {
        if (s.dead || !s.chest) return
        try {
            var be = level.getBlock(s.chest.x, s.chest.y, s.chest.z).getEntity()
            var h = be ? be.getCapability(LB_ItemHandler).resolve().get() : null
            if (!h) return
            for (var i = 0; i < h.getSlots(); i++) {
                var st = h.getStackInSlot(i)
                if (st.isEmpty() || String(st.id) !== "minecraft:written_book" || !st.nbt) continue
                if (String(st.nbt.getString("tfg_book")) !== "diary" || String(st.nbt.getString("author")) !== String(s.name)) continue
                h.extractItem(i, st.getCount(), false)
                h.insertItem(i, dyDiary(level, v, s), false)
                n++
                break
            }
        } catch (e) { }
        // ссылки на клады, что жили в старом дневнике этого жителя, - положить заново
        var drop = r => { if (r && r.ref && r.ref.kind === "дневник" && r.ref.holder === s.name) delete r.ref }
        drop(v.treasury)
        for (var k in (v.stashes || {})) drop(v.stashes[k])
    })
    try { global.tfgLog("tfg books", "поселение " + v.id + ": дневников обновлено " + n) } catch (e) { }
    return n
}

global.TFG_DIARIES = { refresh: (level, v) => dyRefresh(level, v) }
