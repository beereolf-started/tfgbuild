function dyPick(a) { return a[Math.floor(Math.random() * a.length)] }

/** Берёт строку из набора, пока не кончатся неповторённые: в соседних днях одно и то же не пишут. */
function dyDeck(pool) {
    var left = []
    return () => {
        if (!left.length) left = pool.slice().sort(() => Math.random() - 0.5)
        return left.pop()
    }
}

